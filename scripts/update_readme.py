"""Rewrite the README's results section from results/*.json, so no number is typed by hand.

python scripts/update_readme.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from board.app import RULES_FILE, load_rows, model_name, notes, table  # noqa: E402

README = Path(__file__).resolve().parents[1] / "README.md"
START = "<!-- results:start (generated by scripts/update_readme.py) -->"
END = "<!-- results:end -->"
COLUMNS = (
    "model",
    "technique",
    "success % (95% CI)",
    "p50 ms",
    "actions per second",
    "peak MB",
    "compile_s",
    "success GPU",
)


def _table(rows: list[dict]) -> list[str]:
    t = table(rows)
    picks = [t["headers"].index(c) for c in COLUMNS]
    lines = [COLUMNS, ["---"] * len(COLUMNS)]
    lines += [[r[i] for i in picks] for r in t["metadata"]["display_value"]]
    return ["| " + " | ".join(line) + " |" for line in lines]


def _takeaways(rows: list[dict]) -> list[str]:
    """What the rows say. Every number is computed, and a claim appears only if the rows hold it."""
    by_model = {}
    for r in rows:
        by_model.setdefault(r["model"], {})[r["technique"]] = r

    success, compiled, precision = [], [], []
    slower_than_native = True
    for model, techniques in sorted(by_model.items()):
        name = model_name(model)
        scores = [r["success"] for r in techniques.values() if r.get("success") is not None]
        if scores:
            success.append(f"{name} {min(scores):g}–{max(scores):g}%")
        native, fast = techniques.get("native"), techniques.get("compile_autotune")
        if native and fast:
            compiled.append(
                f"{name} {native['p50_ms']:.0f} → {fast['p50_ms']:.0f} ms "
                f"({native['p50_ms'] / fast['p50_ms']:.1f}× speed, "
                f"{fast['compile_s']:.0f} s one-time compile, "
                f"success {native['success']:g}% → {fast['success']:g}%)"
            )
        casts = [techniques[t] for t in ("fp32", "fp16") if t in techniques]
        if native and casts:
            slower_than_native &= all(r["p50_ms"] >= native["p50_ms"] for r in casts)
            times = ", ".join(f"{r['technique']} {r['p50_ms']:.0f}" for r in casts)
            precision.append(f"{name} native {native['p50_ms']:.0f}, {times} ms")

    lines = []
    if success:
        lines.append(f"- **Success:** {', '.join(success)}.")
    if compiled:
        lines.append(f"- **Compile (`compile_autotune` vs `native` p50):** {'; '.join(compiled)}.")
    if precision:
        verdict = "no faster than native" if slower_than_native else "p50"
        lines.append(f"- **Precision (fp32, fp16 {verdict}):** {'; '.join(precision)}.")
    return lines


def render(rows: list[dict], rules_text: str) -> str:
    footnote = ". ".join(n for n in notes(rows, rules_text) if not n.startswith("Compile"))
    return "\n".join([START, *_takeaways(rows), "", *_table(rows), "", f"{footnote}.", END])


def update(readme: Path = README) -> None:
    text = readme.read_text()
    before, rest = text.split(START)
    _, after = rest.split(END)
    block = render(load_rows(), RULES_FILE.read_text())
    readme.write_text(before + block + after)


if __name__ == "__main__":
    update()
